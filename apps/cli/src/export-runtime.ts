import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { ExportRuntime } from '@tooldrop/engine';

// The runtime that exported tools carry (SPEC, Code export): ./export/entry.ts and
// the toolDrop packages it uses, bundled into one plain JavaScript file, with
// third-party packages left as npm dependencies of the exported package. The
// published CLI ships it prebuilt in dist/; a source checkout bundles it on
// first use with esbuild, a development dependency.

const here = (path: string) => fileURLToPath(new URL(path, import.meta.url));
/** The prebuilt files, next to the CLI's bundle (the same path from src/ and from dist/). */
const PREBUILT = { source: here('../dist/export-runtime.js'), meta: here('../dist/export-runtime.json') };

interface CliPackage {
  dependencies: Record<string, string>;
}

/** Bundles the runtime with esbuild: at build time, and from a source checkout. */
export async function bundleExportRuntime(): Promise<ExportRuntime> {
  const { build } = await import('esbuild');
  const cli = JSON.parse(readFileSync(here('../package.json'), 'utf8')) as CliPackage;
  const dependencies = Object.keys(cli.dependencies);
  const result = await build({
    entryPoints: [here('./export/entry.ts')],
    bundle: true,
    write: false,
    platform: 'node',
    format: 'esm',
    target: 'node24',
    external: dependencies.flatMap((name) => [name, `${name}/*`]),
    metafile: true,
    legalComments: 'none',
    banner: {
      js: '// toolDrop runtime (https://github.com/nabeelali0707/toolDrop), Apache-2.0: see LICENSE.\n// Generated by `tooldrop export`; edit tool.json, not this file.',
    },
    logLevel: 'warning',
  });
  const imported = new Set(
    Object.values(result.metafile.outputs).flatMap((output) =>
      output.imports.filter((entry) => entry.external).map((entry) => packageOf(entry.path)),
    ),
  );
  const used = [...imported].filter((name) => !name.startsWith('node:')).sort();
  return {
    source: result.outputFiles[0]?.text ?? '',
    dependencies: Object.fromEntries(used.map((name) => [name, cli.dependencies[name] ?? '*'])),
    // The repository's license: this runs at build time and from a source checkout only.
    license: readFileSync(here('../../../LICENSE'), 'utf8'),
  };
}

/** The runtime for exports: prebuilt when the CLI is installed, bundled now in a source checkout. */
export async function loadExportRuntime(): Promise<ExportRuntime> {
  if (existsSync(PREBUILT.source) && existsSync(PREBUILT.meta)) {
    const meta = JSON.parse(readFileSync(PREBUILT.meta, 'utf8')) as Omit<ExportRuntime, 'source'>;
    return { ...meta, source: readFileSync(PREBUILT.source, 'utf8') };
  }
  return bundleExportRuntime();
}

function packageOf(path: string): string {
  return path
    .split('/')
    .slice(0, path.startsWith('@') ? 2 : 1)
    .join('/');
}
